def build_article_prompt(
    title: str,
    subtitle: Optional[str] = None,
    body: str = "",
    max_body_chars: int = 6000,
) -> str:
    """Construct a clean, formatted prompt for the Gemini AI model.
    
    Args:
        title: Original article headline.
        subtitle: Optional original subtitle or teaser.
        body: Article body text or concatenated paragraphs.
        max_body_chars: Upper character limit to prevent token overflows.
        
    Returns:
        Structured user prompt string.
    """
    clean_title = (title or "").strip()
    clean_sub = (subtitle or "").strip()
    clean_body = (body or "").strip()[:max_body_chars]

    parts: List[str] = [
        "נא לנתח את כתבת הספורט הבאה ולחלץ פלט מובנה לפי ההנחיות והכללים המחייבים:",
        f"כותרת מקורית: {clean_title}",
    ]

    if clean_sub:
        parts.append(f"כותרת משנה מקורית: {clean_sub}")

    if clean_body:
        parts.append(f"\nגוף הכתבה:\n{clean_body}")
    else:
        parts.append("\n(גוף הכתבה קצר או מבוסס על הכותרות)")

    return "\n".join(parts)
